# Дано целое число N(>0), являющееся некоторой степенью числа 2: N = 2^k. Найти целое число K - показатель этой степени.
n = input("Введите число")
k = 0
while type(n) != int:
    try:
        n = int(n)
    except ValueError:
        print("Число ввели неправильно")
        n = input("Введите число")
while n > 1:
    n //= 2
    k += 1
print("Показатель степени:", k)