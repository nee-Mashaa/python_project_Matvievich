# Даны 2 целых числа А и В(А<В). Вывести в порядке убывания все целые числа, расположенные между А и В(включая их),
# а также количество этих чисел
a = int(input("Введите первое число: "))
b = int(input("Введите второе число: "))
if a > b:
    a, b = b, a
count = 0
while a <= b:
    print(b)
    count += 1
    b -= 1
print("Количество чисел между A и B: ", count)