# Посчитать и вывести количество элементов арифметической прогрессии, удовлетворяющих условию 10<ai<30
a = int(input("Введите число:"))
d = int(input("Введите шаг прогрессии:"))
b = int(input("Введите количество чисел ариф прогрессии:"))
n = 0
count = 0
while n < b:
    a += d
    if 10 < a < 30:
        count += 1
    n += 1
print (count)