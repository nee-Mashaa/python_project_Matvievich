# Вывести первые N (N>=3) чисел Фибоначчи и посчитать количесвто четных чисел
a = int(input("Введите количество чисел Фибоначчи большее или равное 3: "))
num_p = 0
n = 0
k = 1
s = 0
while s < a:
    s = n + k
    if s % 2 == 0:
        num_p += 1
    n = k
    k = s
    print("Числа фибоначчи: ", s)
print(num_p)