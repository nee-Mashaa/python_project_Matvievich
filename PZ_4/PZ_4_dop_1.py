# Вывести 4 числа. Найти и вывести на экран сумму и количество отрицательных чисел.
sum_p = 0
sum_n = 0
n = 0
while n < 4:
    num = int(input("Введите число: "))
    if num > 0:
        sum_p += 1
    else:
        sum_n += 1
    n += 1
print("Сумма положительных чисел: ", sum_p, "Сумма отрицательных чисел: ", sum_n)
